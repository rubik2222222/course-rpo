# Эксперимент с числами и битовыми операциями

a = 13  # 1101 в двоичной
b = 10  # 1010 в двоичной

print("Числа:")
print("a =", a, "->", bin(a))
print("b =", b, "->", bin(b))
print()

# Битовые операции
print("Битовые операции:")
print("a & b (И)   =", a & b, "->", bin(a & b))
print("a | b (ИЛИ) =", a | b, "->", bin(a | b))
print("a ^ b (XOR) =", a ^ b, "->", bin(a ^ b))
print("~a    (НЕ)  =", ~a)
print()

# Сдвиги
print("Сдвиги:")
print("a << 1 =", a << 1, "(умножили на 2)")
print("a << 2 =", a << 2, "(умножили на 4)")
print("a >> 1 =", a >> 1, "(разделили на 2)")
print()

# Проверка бита
print("Проверка: установлен ли бит номер 3 у числа a?")
if a & (1 << 3):
    print("Да, бит 3 установлен")
else:
    print("Нет, бит 3 не установлен")
